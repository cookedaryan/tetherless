package com.e2eechat.core.build;

import java.io.IOException;
import java.io.InputStream;
import java.util.Properties;

/**
 * Identifies the build this code is running from.
 *
 * <p>Two things need this. Bug reports are close to useless without a version and a commit, so the
 * About dialog shows both. And more importantly, {@link com.e2eechat.core.network.TlsSupport} needs
 * to know whether it is running from a development tree or from something a user installed: a
 * packaged build must refuse to fall back to the development certificate, whose private key is
 * reproducible by anyone who runs {@code scripts/generate-dev-cert.sh}.
 *
 * <p>The properties file is generated by the build. When it is absent - running from an IDE, or
 * from a test - the channel is {@code dev}, which is the safe default in the sense that matters: it
 * never causes a shipped artifact to be treated as a development one. A release build must
 * positively declare itself.
 */
public final class BuildInfo {

    /** Classpath resource written by the {@code buildInfo} Gradle task. */
    private static final String RESOURCE = "build-info.properties";

    private static final String UNKNOWN = "unknown";
    private static final String RELEASE_CHANNEL = "release";

    private static final Properties PROPERTIES = load();

    private BuildInfo() {
    }

    private static Properties load() {
        Properties properties = new Properties();
        try (InputStream in = BuildInfo.class.getClassLoader().getResourceAsStream(RESOURCE)) {
            if (in != null) {
                properties.load(in);
            }
        } catch (IOException e) {
            // A missing or unreadable stamp is not a reason to fail startup; it only means the
            // build is treated as a development one, which is the conservative direction.
            return new Properties();
        }
        return properties;
    }

    private static String value(String key) {
        String raw = PROPERTIES.getProperty(key);
        return raw == null || raw.trim().isEmpty() ? UNKNOWN : raw.trim();
    }

    /** Project version, for example {@code 1.0.0}. */
    public static String version() {
        return value("version");
    }

    /** Abbreviated git commit the build was made from. */
    public static String commit() {
        return value("commit");
    }

    /** ISO-8601 UTC timestamp of the build. */
    public static String buildTime() {
        return value("buildTime");
    }

    /** {@code release} for a packaged build, {@code dev} otherwise. */
    public static String channel() {
        String declared = PROPERTIES.getProperty("channel");
        return declared == null || declared.trim().isEmpty() ? "dev" : declared.trim();
    }

    /**
     * True only when the build positively declared itself a release.
     *
     * <p>Deliberately not the inverse of some "is development" check: anything unrecognised, absent
     * or malformed reads as development, so a broken stamp can never grant a build the trust that
     * belongs to a packaged one.
     */
    public static boolean isRelease() {
        return RELEASE_CHANNEL.equals(channel());
    }

    /** One-line identification for the About dialog and bug reports. */
    public static String describe() {
        return version() + " (" + commit() + ", " + channel() + ")";
    }
}
